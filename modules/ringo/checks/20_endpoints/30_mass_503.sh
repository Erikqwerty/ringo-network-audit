# shellcheck shell=bash
# Почти все эндпоинты отвечают 503: дело не в маршрутах, а в том, что за прокси не работает приложение.
# Итог: FAIL, если 503 у ≥ 80 % (и проверено хотя бы 5); иначе строки нет.

if (( N_PROBED >= 5 && N_503 * 10 >= N_PROBED * 8 )); then
  printf "   %s↳ %d из %d эндпоинтов ответили 503 — за прокси не работает приложение Ringo (контейнер остановлен или упал),%s\n" "$D" "$N_503" "$N_PROBED" "$N"
  printf "   %s↳ маршруты по отдельности тут ни при чём; проверьте на сервере: docker ps, логи контейнера Ringo%s\n" "$D" "$N"
  [[ "${CH_RES:-}" == placeholder ]] && \
    printf "   %s↳ вместе с сертификатом-заглушкой это типичная картина nginx-proxy, который не видит контейнер Ringo%s\n" "$D" "$N"
  count FAIL "почти все эндпоинты отвечают 503 — приложение Ringo за прокси не работает"
fi
